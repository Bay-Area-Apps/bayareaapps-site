const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '../assets/visits.js'), 'utf8').split('// End pure appointment helpers.')[0];
const sandbox = { Intl, Date, TextEncoder }; vm.createContext(sandbox); vm.runInContext(source, sandbox);
const run = expression => vm.runInContext(expression, sandbox);
const list = expression => Array.from(run(expression));
assert.deepEqual(list("pacificChoices('2027-01-15T10:00')"), ['2027-01-15T18:00:00.000Z']);
assert.deepEqual(list("pacificChoices('2027-07-15T10:00')"), ['2027-07-15T17:00:00.000Z']);
assert.deepEqual(list("pacificChoices('2027-03-14T02:30')"), []);
assert.deepEqual(list("pacificChoices('2026-11-01T01:30')"), ['2026-11-01T08:30:00.000Z', '2026-11-01T09:30:00.000Z']);
assert.deepEqual(list("pacificChoices('2027-02-30T12:00')"), []);
assert.deepEqual(list("pacificChoices('2027-01-01T24:00')"), []);
assert.equal(run("pacificLocalValue('2027-01-01T08:00:00Z')"), '2027-01-01T00:00');
assert.match(run("formatPacificDate('2027-07-15T17:00:00Z')"), /10:00 AM PDT/);
assert.match(run("formatPacificDate('2027-01-15T18:00:00Z')"), /10:00 AM PST/);
const schedule = { id: 'visit-test', status: 'confirmed', scheduledAt: '2027-07-15T17:00:00Z', durationMinutes: 45, version: 3 };
const visit = { petName: 'Dog, Cat; \\ surprise\nLOCATION:Injected', service: 'Care visit', address: '1 Street, City' };
sandbox.schedule = schedule; sandbox.visit = visit;
const calendar = run("visitCalendar(schedule, visit, new Date('2026-10-14T12:00:00Z'))");
assert.ok(calendar.includes('DTSTART:20270715T170000Z\r\nDTEND:20270715T174500Z'));
assert.ok(calendar.includes('SEQUENCE:3\r\nSTATUS:CONFIRMED'));
assert.equal(calendar.match(/\r\nLOCATION:/g).length, 1);
assert.ok(!calendar.includes('#visit='));
assert.ok(calendar.replaceAll('\r\n ', '').includes('Dog\\, Cat\\; \\\\ surprise\\nLOCATION:Injected'));
for (const line of calendar.split('\r\n')) assert.ok(Buffer.byteLength(line) <= 75);
assert.throws(() => run("visitCalendar({...schedule,status:'requested'}, visit)"), /Only a confirmed/);
assert.throws(() => run("visitCalendar({...schedule,status:'cancelled'}, visit)"), /Only a confirmed/);
const unicode = run("foldCalendarLine('DESCRIPTION:' + '🐾é'.repeat(90))");
for (const line of unicode.split('\r\n')) assert.ok(Buffer.byteLength(line) <= 75);
assert.equal(unicode.replaceAll('\r\n ', ''), 'DESCRIPTION:' + '🐾é'.repeat(90));
console.log('PASS: 15 Pacific/DST, invalid-time, confirmed-only ICS, escaping, duration, and Unicode folding checks.');
